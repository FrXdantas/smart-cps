"""Descoberta de fontes e mapeamento classe→arquivo (portado de scan/group_units/...)."""

import os
import re
from pathlib import Path

from .constants import C_FAMILY_EXTS

PACKAGE_RE = re.compile(r"^\s*package\s+([\w\.]+)", re.M)
JAVA_CLASS_RE = re.compile(
    r"\b(?:public\s+)?(?:final\s+|abstract\s+)?"
    r"(?:class|interface|enum|record)\s+(\w+)"
)
KOTLIN_CLASS_RE = re.compile(
    r"\b(?:open\s+|abstract\s+|sealed\s+|data\s+|enum\s+)?"
    r"class\s+(\w+)"
)


def scan(folder: str) -> tuple[list[str], list[str], list[str]]:
    """Localiza .java / .kt / C-família (.c/.cpp/.cc/.cxx/.c++), ignorando
    artefatos gerados (_FIXED, _LTL, testes). C e C++ vão no mesmo balde: ambos
    são verificados pelo ESBMC, que distingue a linguagem pela extensão."""
    java_files, kotlin_files, c_files = [], [], []
    for root, _, files in os.walk(folder):
        for f in files:
            full = os.path.join(root, f)
            if f.endswith(".java") and "_FIXED" not in f and "AutoGeneratedTest" not in f:
                java_files.append(full)
            elif f.endswith(".kt") and "_FIXED" not in f:
                kotlin_files.append(full)
            elif f.endswith(C_FAMILY_EXTS) and "_FIXED" not in f and "_LTL" not in f:
                c_files.append(full)
    return java_files, kotlin_files, c_files


def read_text(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            return f.read()
    except Exception:
        return ""


def extract_package(text: str) -> str:
    m = PACKAGE_RE.search(text)
    return m.group(1) if m else ""


def classes_generated(base_dir: str) -> list[str]:
    """Nomes totalmente qualificados das classes .class geradas (ignora inner $)."""
    out = []
    for root, _, files in os.walk(base_dir):
        for f in files:
            if f.endswith(".class"):
                rel = os.path.relpath(os.path.join(root, f), base_dir)
                name = rel.replace(os.sep, ".").replace("/", ".")[:-6]
                if "$" not in name:
                    out.append(name)
    return out


def group_units(java_files: list[str], kt_files: list[str]) -> dict:
    """Agrupa fontes JVM por diretório (uma pasta = uma unidade de compilação)."""
    units: dict[str, dict] = {}
    for jf in java_files:
        d = os.path.dirname(os.path.abspath(jf))
        units.setdefault(d, {"java": [], "kt": []})["java"].append(jf)
    for kf in kt_files:
        d = os.path.dirname(os.path.abspath(kf))
        units.setdefault(d, {"java": [], "kt": []})["kt"].append(kf)
    return units


def unit_build_dir(unit_dir: str, root: str, build_dir: str) -> str:
    """Diretório de saída de bytecode para uma unidade, sob `build_dir`."""
    rel = os.path.relpath(unit_dir, root)
    safe = rel.replace(os.sep, "__").replace(".", "_") or "_root"
    path = os.path.join(build_dir, safe)
    Path(path).mkdir(parents=True, exist_ok=True)
    return path


def map_classes_to_sources(java_files: list[str], kotlin_files: list[str]) -> dict[str, str]:
    """Mapeia nome qualificado de classe → arquivo-fonte (Java e Kotlin)."""
    mapping: dict[str, str] = {}
    for jf in java_files:
        text = read_text(jf)
        pkg = extract_package(text)
        for cls in JAVA_CLASS_RE.findall(text):
            mapping[f"{pkg}.{cls}" if pkg else cls] = jf
        base = os.path.splitext(os.path.basename(jf))[0]
        mapping.setdefault(f"{pkg}.{base}" if pkg else base, jf)
    for kf in kotlin_files:
        text = read_text(kf)
        pkg = extract_package(text)
        for cls in KOTLIN_CLASS_RE.findall(text):
            mapping[f"{pkg}.{cls}" if pkg else cls] = kf
        base = os.path.splitext(os.path.basename(kf))[0]
        # Facade de arquivo Kotlin: 'main.kt' → 'MainKt'.
        facade = (base[:1].upper() + base[1:] + "Kt") if base else "Kt"
        mapping.setdefault(f"{pkg}.{facade}" if pkg else facade, kf)
    return mapping
